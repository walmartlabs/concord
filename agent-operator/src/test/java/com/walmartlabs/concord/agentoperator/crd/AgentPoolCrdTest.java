import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.dataformat.yaml.YAMLFactory;
import org.junit.jupiter.api.Test;

import java.nio.file.Path;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Checks the CRD generated by crd-generator-maven-plugin into deploy/crds.
 * Kubernetes prunes fields missing from a structural schema and rejects values
 * that do not match it.
 */
public class AgentPoolCrdTest {

    private static final Path CRD = Path.of("deploy/crds/agentpools.concord.walmartlabs.com-v1.yml");

    @Test
    public void schemaCoversAllConfigurationProperties() throws Exception {
        JsonNode specProperties = specSchema().path("properties");

        @SuppressWarnings("unchecked")
        Map<String, Object> cfg = new ObjectMapper().convertValue(new AgentPoolConfiguration(), Map.class);

        Set<String> missing = new TreeSet<>();
        for (String name : cfg.keySet()) {
            if (!specProperties.has(name)) {
                missing.add(name);
            }
        }

        assertTrue(missing.isEmpty(), "AgentPool CRD is missing spec properties (they would be pruned): " + missing);
    }

    @Test
    public void queueSelectorAcceptsArbitraryValues() throws Exception {
        // queueSelector holds both objects (agent.flavor) and lists (queryParams)
        JsonNode queueSelector = specSchema().path("properties").path("queueSelector");

        assertEquals("object", queueSelector.path("type").asText());
        assertTrue(queueSelector.path("x-kubernetes-preserve-unknown-fields").asBoolean(),
                "queueSelector must preserve unknown fields");
        assertFalse(queueSelector.has("additionalProperties"),
                "queueSelector values must not be restricted to a single type");
    }

    private static JsonNode specSchema() throws Exception {
        JsonNode crd = new ObjectMapper(new YAMLFactory()).readTree(CRD.toFile());
        JsonNode version = crd.path("spec").path("versions").get(0);
        assertNotNull(version, "CRD has no versions");
        return version.path("schema").path("openAPIV3Schema").path("properties").path("spec");
    }
}
